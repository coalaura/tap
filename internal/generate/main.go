package main

import (
	"bytes"
	"errors"
	"fmt"
	"go/format"
	"io"
	"os"
	"path/filepath"
	"slices"
	"strings"

	"github.com/coalaura/tap/internal/catalog"
	"github.com/goccy/go-yaml"
)

func main() {
	err := generate()
	if err != nil {
		fmt.Fprintln(os.Stderr, err)

		os.Exit(1)
	}
}

func generate() error {
	definitions, err := loadPackages("packages")
	if err != nil {
		return err
	}

	var output bytes.Buffer

	output.WriteString("// Code generated by go generate; DO NOT EDIT.\n\npackage main\n\nimport \"github.com/coalaura/tap/internal/catalog\"\n\nvar packageCatalog = []catalog.Package{\n")

	for index := range definitions {
		fmt.Fprintf(&output, "%#v,\n", definitions[index])
	}

	output.WriteString("}\n")

	formatted, err := format.Source(output.Bytes())
	if err != nil {
		return err
	}

	return os.WriteFile("packages_gen.go", formatted, 0644)
}

func loadPackages(directory string) ([]catalog.Package, error) {
	entries, err := os.ReadDir(directory)
	if err != nil {
		return nil, err
	}

	definitions := make([]catalog.Package, 0, len(entries))
	names := make(map[string]struct{}, len(entries))

	for _, entry := range entries {
		if entry.IsDir() || filepath.Ext(entry.Name()) != ".yml" {
			continue
		}

		path := filepath.Join(directory, entry.Name())

		definition, err := loadPackage(path)
		if err != nil {
			return nil, fmt.Errorf("%s: %w", path, err)
		}

		if _, exists := names[definition.Name]; exists {
			return nil, fmt.Errorf("%s: duplicate package %q", path, definition.Name)
		}

		names[definition.Name] = struct{}{}
		definitions = append(definitions, definition)
	}

	if len(definitions) == 0 {
		return nil, errors.New("no packages/*.yml definitions found")
	}

	slices.SortFunc(definitions, func(left, right catalog.Package) int {
		return strings.Compare(left.Name, right.Name)
	})

	return definitions, nil
}

func loadPackage(path string) (catalog.Package, error) {
	name := strings.TrimSuffix(filepath.Base(path), ".yml")

	definition := catalog.Package{
		Name:   name,
		Source: "github",
		Prefix: "v",
		Binary: name,
		Asset:  "{binary}-{os}-{arch}{ext}",
	}

	file, err := os.Open(path)
	if err != nil {
		return definition, err
	}

	defer file.Close()

	decoder := yaml.NewDecoder(file, yaml.Strict())

	err = decoder.Decode(&definition)
	if err != nil {
		return definition, err
	}

	var extra catalog.Package

	err = decoder.Decode(&extra)
	if !errors.Is(err, io.EOF) {
		return definition, errors.New("expected exactly one YAML document")
	}

	if definition.Platforms == nil {
		definition.Platforms = map[string]catalog.Target{
			"linux-amd64":   {},
			"windows-amd64": {},
		}
	}

	if definition.Args == nil {
		argument := "--version"
		if definition.Source == "go" || definition.Source == "zig" {
			argument = "version"
		}

		definition.Args = []string{argument}
	}

	err = validatePackage(&definition)

	return definition, err
}
